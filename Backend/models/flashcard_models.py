from pydantic import BaseModel, Field

class Flashcard(BaseModel):

    front: str = Field (description="The questions or prompt displayed on the front of the flashcard.")

    back: str = Field(description="The correct asnwer displayed on the back of the flashcard.")
    
    explanation: str = Field(
        min_length= 1,
        max_length= 400, 
        description="a concise explanation of the correct answer, limited to 300 characters."
    )


class GeneratedFlaschcards(BaseModel):
    flashcards: list[Flashcard] = Field(description="The collection of flashcards generated by the AI model.")

class FlashcardResponse(BaseModel):
    quizId: int = Field(description="The identifier of the original quiz associated with the flashcard.")

    flashcards: list[Flashcard] = Field(description="The generated flashcards associated with the specified quiz.")
